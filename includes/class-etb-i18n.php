if ( ! defined( 'ABSPATH' ) ) exit;

class ETB_I18n {

    public static function lang() {
        return 'en';
    }

    public static function is_fr() {
        return false;
    }

    /**
     * Traduit un texte anglais source. Retourne le texte inchangé en anglais
     * ou si aucune traduction française n'est disponible.
     */
    public static function t( $text ) {
        if ( ! self::is_fr() ) {
            return $text;
        }
        $map = self::fr_map();
        return isset( $map[ $text ] ) ? $map[ $text ] : $text;
    }

    /** Date localisée selon la langue du site (mois FR ou EN automatiquement). */
    public static function date( $format, $timestamp ) {
        if ( function_exists( 'date_i18n' ) ) {
            return date_i18n( $format, $timestamp );
        }
        return date( $format, $timestamp );
    }

    /** Payload transmis au JS via wp_localize_script. */
    public static function js_payload() {
        return array(
            'lang' => self::lang(),
            'fr'   => self::is_fr() ? self::fr_map() : array(),
        );
    }

